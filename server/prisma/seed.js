async function main() {
  console.log('🌱 Сидирование базы данных UVYANTRA...');

  // --- Материалы ---
  for (const [i, m] of MATERIALS.entries()) {
    await prisma.material.upsert({
      where: { name: m.name },
      update: {},
      create: { ...m, order: i },
    });
  }
  console.log(`  ✓ Материалы: ${MATERIALS.length}`);

  // --- Изделия ---
  for (const [i, name] of ITEM_TYPES.entries()) {
    await prisma.itemType.upsert({
      where: { name },
      update: {},
      create: { name, order: i },
    });
  }
  console.log(`  ✓ Изделия: ${ITEM_TYPES.length}`);

  // --- Услуги ---
  let svcCount = 0;
  for (const [category, names] of Object.entries(SERVICES)) {
    for (const [i, name] of names.entries()) {
      await prisma.serviceCatalog.upsert({
        where: { category_name: { category, name } },
        update: {},
        create: { category, name, order: i },
      });
      svcCount++;
    }
  }
  console.log(`  ✓ Услуги: ${svcCount}`);

  // --- Сотрудники ---
  for (const emp of EMPLOYEES) {
    const passwordHash = await bcrypt.hash(emp.password, 10);
    await prisma.user.upsert({
      where: { login: emp.login },
      update: {},
      create: {
        login: emp.login,
        passwordHash,
        name: emp.name,
        role: emp.role,
        percent: emp.percent,
        bonus: emp.bonus,
      },
    });
  }
  console.log(`  ✓ Сотрудники: ${EMPLOYEES.length} (admin/uvyantra2024, master/1234)`);

  // --- Клиенты ---
  for (const c of CLIENTS) {
    await prisma.client.upsert({
      where: { phone: c.phone },
      update: {},
      create: c,
    });
  }
  console.log(`  ✓ Клиенты: ${CLIENTS.length}`);

  console.log('✅ Сидирование завершено');
}

main()
  .catch(e => { console.error(e); process.exit(1); })
